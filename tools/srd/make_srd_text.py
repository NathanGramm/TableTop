#!/usr/bin/env python3
"""Writes scripts/data/srd_text.gd: rules text from the SRD 5.1 (CC BY 4.0) for the in-game hover cards.

Source: the 5e-bits/5e-database JSON (2014 SRD). Usage, from the repo root:
    python3 tools/srd/make_srd_text.py [dir with the JSON files]
Without a directory it downloads them from GitHub.
"""
import json, re, sys, urllib.request
from pathlib import Path

URL = "https://raw.githubusercontent.com/5e-bits/5e-database/main/src/2014/en/5e-SRD-%s.json"
ROOT = Path(__file__).resolve().parents[2]

# Hotbar tile title -> SRD feature name, for titles that differ from the SRD's.
FEATURES = {
    "Second Wind": "Second Wind", "Action Surge": "Action Surge (1 use)", "Rage": "Rage", "End Rage": "Rage",
    "Frenzy": "Frenzy", "Flurry of Blows": "Flurry of Blows", "Patient Defense": "Patient Defense",
    "Step: Dash": "Step of the Wind", "Step: Disengage": "Step of the Wind", "Sacred Weapon": "Channel Divinity: Sacred Weapon",
    "Lay on Hands": "Lay on Hands", "Inspire": "Bardic Inspiration (d6)", "Font of Magic": "Font of Magic",
    "Wild Shape": "Wild Shape (CR 1/4 or below, no flying or swim speed)", "Revert Form": "Wild Shape (CR 1/4 or below, no flying or swim speed)",
    "Turn Undead": "Channel Divinity: Turn Undead", "Arcane Recovery": "Arcane Recovery",
}
# Hotbar tile title -> (rule section, sub-heading).
RULES = {
    "Dash": ("Actions in Combat", "Dash"), "Disengage": ("Actions in Combat", "Disengage"), "Dodge": ("Actions in Combat", "Dodge"),
    "Help": ("Actions in Combat", "Help"), "Hide": ("Actions in Combat", "Hide"), "Ready": ("Actions in Combat", "Ready"),
    "Grapple": ("Making an Attack", "Grappling"), "Escape": ("Making an Attack", "Grappling"),
    "Shove": ("Making an Attack", "Shoving a Creature"), "Push": ("Making an Attack", "Shoving a Creature"),
    "Stand Up": ("Movement and Position", "Being Prone"), "Stabilize": ("Damage and Healing", "Stabilizing a Creature"),
}
# Game spell names the SRD spells differently.
SPELL_NAMES = {"Tasha's Hideous Laughter": "Hideous Laughter"}


def load(name, src):
    if src:
        return json.loads((Path(src) / ("5e-SRD-%s.json" % name)).read_text())
    with urllib.request.urlopen(URL % name) as f:
        return json.loads(f.read())


def para(lines):
    return "\n".join(l.strip() for l in lines if l.strip())


def section(md, heading):
    m = re.search(r"^(#+) %s\n(.*?)(?=^#{1,%d} |\Z)" % (re.escape(heading), 9), md, re.M | re.S)
    if not m:
        raise SystemExit("no section " + heading)
    level = len(m.group(1))
    body = re.split(r"^#{1,%d} " % level, m.group(2), flags=re.M)[0]
    body = re.sub(r"^#+ (.*)$", r"\1.", body, flags=re.M)  # sub-headings inline
    return re.sub(r"\n{2,}", "\n", body.replace("***", "").replace("**", "").replace("*", "")).strip()


def gd(v):
    return json.dumps(v, ensure_ascii=True)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    srd_spells = {s["name"].lower(): s for s in load("Spells", src)}
    feats = {f["name"]: f for f in load("Features", src)}
    rules = {r["name"]: r["desc"] for r in load("Rule-Sections", src)}
    conds = load("Conditions", src)
    props = load("Weapon-Properties", src)

    spells = {}
    text = (ROOT / "scripts/data/spells.gd").read_text()
    for sid, name in re.findall(r'^\t"([a-z_]+)": \{"name": "([^"]+)"', text, re.M):
        s = srd_spells.get(SPELL_NAMES.get(name, name).lower())
        if s is None:
            continue  # not in the SRD: the card falls back to the game's own summary
        comp = ", ".join(s["components"]) + (" (%s)" % s["material"].rstrip(".") if s.get("material") else "")
        spells[sid] = {"casting_time": s["casting_time"], "range": s["range"], "components": comp,
            "duration": ("Concentration, " + s["duration"][0].lower() + s["duration"][1:]) if s["concentration"] else s["duration"],
            "text": para(s["desc"]), "higher": para(s.get("higher_level", []))}
    tiles = {t: para(feats[n]["desc"]) for t, n in FEATURES.items()}
    tiles.update({t: section(rules[sec], h) for t, (sec, h) in RULES.items()})

    out = ["class_name SrdText",
           "## Rules text from the System Reference Document 5.1 (CC BY 4.0), for hover cards.",
           "## Generated by tools/srd/make_srd_text.py; don't edit by hand.", ""]
    out.append("const SPELLS := " + gd(spells))
    out.append("const TILES := " + gd(tiles))
    out.append("const CONDITIONS := " + gd({c["index"]: para(c["desc"]) for c in conds}))
    out.append("const WEAPON_PROPERTIES := " + gd({p["index"]: para(p["desc"]) for p in props}))
    (ROOT / "scripts/data/srd_text.gd").write_text("\n".join(out) + "\n")
    print("%d spells, %d tiles" % (len(spells), len(tiles)))


main()
